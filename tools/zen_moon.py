"""The moon's face for Hotaru (drawn seas read as "a peanut"): the near side of a real map,
NASA's CGI Moon Kit (public domain, assets/images/README.md), seen straight on (an orthographic view of the
equirectangular map: longitude 0 in the middle), averaged down to N x N brightness (0 outside the disc), its
brightness stretched so the darkest seas are 0 and the brightest highlands 255 (the scene sets the shades).

    tools/zen_moon.py [assets/images/moon-lroc-color-1k.jpg] [firmware/src/app/zen_moon.h]
"""
import math
import sys

from PIL import Image

N = 40
SS = 6                                            # samples a cell, each way


def main(src, dst):
    im = Image.open(src).convert("L")
    W, H = im.size
    px = im.load()
    cells = [[None] * N for _ in range(N)]
    for j in range(N):
        for i in range(N):
            acc, n = 0.0, 0
            for b in range(SS):
                for a in range(SS):
                    u = ((i + (a + 0.5) / SS) / N) * 2.0 - 1.0
                    v = ((j + (b + 0.5) / SS) / N) * 2.0 - 1.0
                    r2 = u * u + v * v
                    if r2 >= 1.0:
                        continue
                    z = math.sqrt(1.0 - r2)
                    lat = math.asin(-v)
                    lon = math.atan2(u, z)
                    x = (lon / (2 * math.pi) + 0.5) * W
                    y = (0.5 - lat / math.pi) * H
                    acc += px[min(W - 1, int(x)), min(H - 1, int(y))]
                    n += 1
            cells[j][i] = acc / n if n * 2 >= SS * SS else None   # (half the cell on the disc, or outside)
    vals = sorted(c for row in cells for c in row if c is not None)
    lo, hi = vals[int(len(vals) * 0.03)], vals[int(len(vals) * 0.97)]
    out = []
    for row in cells:
        out.append([0 if c is None else max(1, min(255, int(round((c - lo) / (hi - lo) * 254.0)) + 1)) for c in row])
    with open(dst, "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n")
        f.write("/* Generated by tools/zen_moon.py from NASA's CGI Moon Kit (public domain): the moon's near side, %d x %d,\n"
                " * brightness 1 (the darkest seas) .. 255 (the brightest highlands), 0 off the disc. Do not edit. */\n" % (N, N))
        f.write("#pragma once\n#define ZN_MOON_N %d\nstatic const uint8_t ZN_MOON[ZN_MOON_N * ZN_MOON_N] = {\n" % N)
        for row in out:
            f.write("    " + ", ".join("%d" % v for v in row) + ",\n")
        f.write("};\n")
    print("moon: %s (%d x %d)" % (dst, N, N))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "assets/images/moon-lroc-color-1k.jpg",
         sys.argv[2] if len(sys.argv) > 2 else "firmware/src/app/zen_moon.h")
